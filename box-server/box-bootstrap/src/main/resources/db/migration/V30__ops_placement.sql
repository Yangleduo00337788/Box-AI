CREATE TABLE ops_placement (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    slot VARCHAR(32) NOT NULL COMMENT 'CHAT_HOME/GLOBAL_ALERT/MARKET_SPOTLIGHT',
    kind VARCHAR(32) NOT NULL COMMENT 'ANNOUNCEMENT/PROMO',
    title VARCHAR(128) NOT NULL,
    body VARCHAR(1024) DEFAULT NULL,
    link_url VARCHAR(512) DEFAULT NULL,
    link_label VARCHAR(64) DEFAULT NULL,
    theme VARCHAR(16) NOT NULL DEFAULT 'info' COMMENT 'info/success/warning/error',
    dismissible TINYINT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL DEFAULT 'LISTED' COMMENT 'LISTED/UNLISTED',
    sort_order INT NOT NULL DEFAULT 0,
    starts_at DATETIME(3) DEFAULT NULL,
    ends_at DATETIME(3) DEFAULT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_ops_placement_slot (slot, status, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='平台运营位';
